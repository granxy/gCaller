-- DESTRUCTIVE RESET: this drops GCaller profiles, call history, and call signals.
-- Supabase auth.users accounts are preserved, but every GCaller number is regenerated.
-- Run in the SAME Supabase project used by supabase-client.js.

-- Remove existing GCaller auth triggers that write to the old profile table.
do $$
declare tr record;
begin
  for tr in
    select t.tgname
    from pg_trigger t
    where t.tgrelid = 'auth.users'::regclass
      and not t.tgisinternal
      and (
        t.tgname ilike '%gcaller%'
        or pg_get_functiondef(t.tgfoid) ilike '%gcaller_profiles%'
      )
  loop
    execute format('drop trigger %I on auth.users', tr.tgname);
  end loop;
end;
$$;

-- Remove policies from only the three GCaller tables being reset.
do $$
declare p record;
begin
  for p in
    select tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('gcaller_signals', 'gcaller_calls', 'gcaller_profiles')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end;
$$;

-- Remove old GCaller RPCs before replacing their tables.
drop function if exists public.gcaller_send_signal(uuid, text, jsonb);
drop function if exists public.gcaller_start_call(uuid);
drop function if exists public.gcaller_call_peer(uuid);
drop function if exists public.lookup_gcaller_user(text);
drop function if exists public.gcaller_is_call_participant(uuid);
drop function if exists public.gcaller_generate_number();
drop function if exists public.gcaller_handle_new_auth_user();

-- Drop only the old app tables. Supabase auth.users is not dropped.
drop table if exists public.gcaller_signals;
drop table if exists public.gcaller_calls;
drop table if exists public.gcaller_profiles;

create table public.gcaller_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  gcaller_number text not null unique check (gcaller_number ~ '^[0-9]{10}$'),
  country_code text not null default '1',
  created_at timestamptz not null default now()
);

create table public.gcaller_calls (
  id uuid primary key default gen_random_uuid(),
  caller_id uuid not null references auth.users(id) on delete cascade,
  callee_id uuid not null references auth.users(id) on delete cascade,
  caller_number text not null,
  callee_number text not null,
  status text not null default 'ringing',
  created_at timestamptz not null default now(),
  answered_at timestamptz,
  ended_at timestamptz,
  check (caller_id <> callee_id)
);
create index gcaller_calls_caller_created_idx on public.gcaller_calls(caller_id, created_at desc);
create index gcaller_calls_callee_created_idx on public.gcaller_calls(callee_id, created_at desc);

create table public.gcaller_signals (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.gcaller_calls(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('offer', 'answer', 'ice', 'hangup')),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index gcaller_signals_call_id_id_idx on public.gcaller_signals(call_id, id);

-- Regenerate profiles for existing Supabase auth accounts.
create function public.gcaller_generate_number()
returns text
language plpgsql
volatile
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_number text;
begin
  perform pg_catalog.pg_advisory_xact_lock(78123451);
  loop
    v_number := '1' || pg_catalog.lpad(
      pg_catalog.floor(pg_catalog.random() * 1000000000)::bigint::text,
      9,
      '0'
    );
    exit when not exists (
      select 1 from public.gcaller_profiles p where p.gcaller_number = v_number
    );
  end loop;
  return v_number;
end;
$function$;

-- Backfill existing auth accounts; account passwords and auth IDs remain unchanged.
do $$
declare
  u record;
  v_base text;
  v_username text;
  v_number text;
begin
  for u in
    select id, email, raw_user_meta_data
    from auth.users
    order by created_at
  loop
    v_base := pg_catalog.lower(pg_catalog.regexp_replace(
      coalesce(
        nullif(u.raw_user_meta_data->>'username', ''),
        nullif(pg_catalog.split_part(coalesce(u.email, ''), '@', 1), ''),
        'user_' || pg_catalog.substr(pg_catalog.replace(u.id::text, '-', ''), 1, 8)
      ),
      '[^a-zA-Z0-9_]', '', 'g'
    ));
    if pg_catalog.length(v_base) < 3 then
      v_base := 'user_' || pg_catalog.substr(pg_catalog.replace(u.id::text, '-', ''), 1, 8);
    end if;
    v_username := pg_catalog.left(v_base, 24);
    if exists (select 1 from public.gcaller_profiles p where p.username = v_username) then
      v_username := pg_catalog.left(v_base, 15) || '_' || pg_catalog.substr(pg_catalog.replace(u.id::text, '-', ''), 1, 8);
    end if;
    v_number := public.gcaller_generate_number();
    insert into public.gcaller_profiles(user_id, username, gcaller_number, country_code)
    values (
      u.id,
      v_username,
      v_number,
      coalesce(nullif(u.raw_user_meta_data->>'country_code', ''), '1')
    );
  end loop;
end;
$$;

-- Create a profile automatically for future signups.
create function public.gcaller_handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_base text;
  v_username text;
  v_number text;
begin
  v_base := pg_catalog.lower(pg_catalog.regexp_replace(
    coalesce(
      nullif(new.raw_user_meta_data->>'username', ''),
      nullif(pg_catalog.split_part(coalesce(new.email, ''), '@', 1), ''),
      'user_' || pg_catalog.substr(pg_catalog.replace(new.id::text, '-', ''), 1, 8)
    ),
    '[^a-zA-Z0-9_]', '', 'g'
  ));
  if pg_catalog.length(v_base) < 3 then
    v_base := 'user_' || pg_catalog.substr(pg_catalog.replace(new.id::text, '-', ''), 1, 8);
  end if;
  v_username := pg_catalog.left(v_base, 24);
  if exists (select 1 from public.gcaller_profiles p where p.username = v_username) then
    v_username := pg_catalog.left(v_base, 15) || '_' || pg_catalog.substr(pg_catalog.replace(new.id::text, '-', ''), 1, 8);
  end if;
  v_number := public.gcaller_generate_number();
  insert into public.gcaller_profiles(user_id, username, gcaller_number, country_code)
  values (new.id, v_username, v_number, coalesce(nullif(new.raw_user_meta_data->>'country_code', ''), '1'))
  on conflict (user_id) do nothing;
  return new;
end;
$function$;
create trigger gcaller_profile_after_auth_insert
after insert on auth.users
for each row execute function public.gcaller_handle_new_auth_user();

-- Secure participant check shared by read policies and RPCs.
create function public.gcaller_is_call_participant(p_call_id uuid)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $function$
  select exists (
    select 1 from public.gcaller_calls c
    where c.id = p_call_id
      and (c.caller_id = auth.uid() or c.callee_id = auth.uid())
  );
$function$;

-- User lookup is normalized and never returns the signed-in user as a target.
create function public.lookup_gcaller_user(p_number text)
returns table(user_id uuid, username text, gcaller_number text)
language sql
stable
security definer
set search_path = pg_catalog, public
as $function$
  select p.user_id, p.username, p.gcaller_number
  from public.gcaller_profiles p
  where pg_catalog.regexp_replace(p.gcaller_number, '[^0-9]', '', 'g')
      = pg_catalog.regexp_replace(p_number, '[^0-9]', '', 'g')
    and pg_catalog.length(pg_catalog.regexp_replace(p_number, '[^0-9]', '', 'g')) = 10
    and p.user_id <> auth.uid()
  order by p.user_id
  limit 1;
$function$;

-- Resolve the other participant's display name only for an actual call participant.
create function public.gcaller_call_peer(p_user_id uuid)
returns table(username text, gcaller_number text)
language sql
stable
security definer
set search_path = pg_catalog, public
as $function$
  select p.username, p.gcaller_number
  from public.gcaller_profiles p
  where p.user_id = p_user_id
    and exists (
      select 1 from public.gcaller_calls c
      where (c.caller_id = p_user_id and c.callee_id = auth.uid())
         or (c.callee_id = p_user_id and c.caller_id = auth.uid())
    )
  limit 1;
$function$;

-- Create calls through a validated RPC rather than a direct table INSERT.
create function public.gcaller_start_call(p_callee_id uuid)
returns setof public.gcaller_calls
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_caller_id uuid := auth.uid();
  v_caller_number text;
  v_callee_number text;
  v_call public.gcaller_calls%rowtype;
begin
  if v_caller_id is null then
    raise exception 'You must be signed in to start a call' using errcode = '42501';
  end if;
  if p_callee_id is null or p_callee_id = v_caller_id then
    raise exception 'Choose another registered user to call' using errcode = '22023';
  end if;
  select p.gcaller_number into v_caller_number
  from public.gcaller_profiles p where p.user_id = v_caller_id;
  if not found or v_caller_number is null then
    raise exception 'Your GCaller profile or number could not be found';
  end if;
  select p.gcaller_number into v_callee_number
  from public.gcaller_profiles p where p.user_id = p_callee_id;
  if not found or v_callee_number is null then
    raise exception 'The selected user does not have a GCaller number';
  end if;
  insert into public.gcaller_calls(caller_id, callee_id, caller_number, callee_number, status)
  values (v_caller_id, p_callee_id, v_caller_number, v_callee_number, 'ringing')
  returning * into v_call;
  return next v_call;
  return;
end;
$function$;

-- Signal inserts are validated and performed by this narrowly scoped RPC.
create function public.gcaller_send_signal(
  p_call_id uuid,
  p_kind text,
  p_payload jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'You must be signed in to send call signals' using errcode = '42501';
  end if;
  if p_kind is null or p_kind not in ('offer', 'answer', 'ice', 'hangup') then
    raise exception 'Invalid call signal type' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.gcaller_calls c
    where c.id = p_call_id
      and (c.caller_id = v_user_id or c.callee_id = v_user_id)
  ) then
    raise exception 'This user is not a participant in that call' using errcode = '42501';
  end if;
  insert into public.gcaller_signals(call_id, sender_id, kind, payload)
  values (p_call_id, v_user_id, p_kind, coalesce(p_payload, '{}'::jsonb));
end;
$function$;

-- Restrict table access to each user's own profile and call participants.
alter table public.gcaller_profiles enable row level security;
alter table public.gcaller_calls enable row level security;
alter table public.gcaller_signals enable row level security;

create policy "gcaller user reads own profile"
on public.gcaller_profiles for select to authenticated
using (user_id = auth.uid());

create policy "gcaller participants read calls"
on public.gcaller_calls for select to authenticated
using (caller_id = auth.uid() or callee_id = auth.uid());

create policy "gcaller participants update calls"
on public.gcaller_calls for update to authenticated
using (caller_id = auth.uid() or callee_id = auth.uid())
with check (caller_id = auth.uid() or callee_id = auth.uid());

create policy "gcaller participants read signals"
on public.gcaller_signals for select to authenticated
using (public.gcaller_is_call_participant(call_id));

-- Only authenticated users may execute the RPCs; table writes are validated inside them.
revoke all on function public.gcaller_generate_number() from public;
revoke all on function public.gcaller_handle_new_auth_user() from public;
revoke all on function public.gcaller_is_call_participant(uuid) from public;
revoke all on function public.lookup_gcaller_user(text) from public;
revoke all on function public.gcaller_call_peer(uuid) from public;
revoke all on function public.gcaller_start_call(uuid) from public;
revoke all on function public.gcaller_send_signal(uuid, text, jsonb) from public;
grant execute on function public.gcaller_is_call_participant(uuid) to authenticated;
grant execute on function public.lookup_gcaller_user(text) to authenticated;
grant execute on function public.gcaller_call_peer(uuid) to authenticated;
grant execute on function public.gcaller_start_call(uuid) to authenticated;
grant execute on function public.gcaller_send_signal(uuid, text, jsonb) to authenticated;

